#ifndef P1600_SCREEN_H
#define P1600_SCREEN_H

#include <stdbool.h>
#include <stdint.h>

/*
 * P1600dn halftoning into the printer's 1- and 2-bit video data.
 *
 * Input is one line of 8-bit CUPS_CSPACE_W luminance (0 = black, 255 = white).
 * Output is MSB-first video data, 1 = toner: two bits per pixel for FastRes
 * 1200 (bpp 2, 12x12 four-level screen) or one bit per pixel for 600 dpi
 * (bpp 1, 16x16 threshold screen).  `out` must be zeroed by the caller.
 *
 * `remaining` is a descending line counter: the 12-line-rounded page
 * height on the first line, minus one on every following line.  It selects
 * the screen row. The screens themselves are the project's own
 * (src/p1600_screen_tables.h, generated by tools/gen_screens.py).
 */
void p1600_screen_line(const uint8_t *gray, uint32_t width, uint32_t bpp,
                    uint32_t remaining, uint8_t *out);

/* On arm64 p1600_screen_line() screens 48 (FastRes) or 16 (600 dpi) pixels per
 * NEON step and leaves the line's tail to the scalar code below; the bytes
 * are the same. The scalar screen is exported so tests can compare. */
void p1600_screen_line_scalar(const uint8_t *gray, uint32_t width, uint32_t bpp,
                           uint32_t remaining, uint8_t *out);

/* True when the FastRes NEON path is in use (the table's cells are monotonic). */
bool p1600_screen_simd_active(void);

#endif /* P1600_SCREEN_H */
